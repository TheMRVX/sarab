"""Generate redistributable notices from cargo-about and license-checker results.

Inputs MUST be from the exact Cargo.lock and npm package-lock.json used to build.
The generated report is not a substitute for auditing native/asset dependencies.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fence(text: str) -> str:
    """Use a Markdown fence longer than any runs of tildes in license text."""
    longest = max((len(m.group()) for m in re.finditer(r"~+", text)), default=0)
    return "~" * max(4, longest + 1)


def generate(rust: Path, frontend_json: Path, repo_root: Path) -> str:
    rust_text = rust.read_text(encoding="utf-8-sig").strip()
    if not rust_text or "## " not in rust_text:
        raise ValueError("Rust notices are empty or not generated by cargo-about")

    packages = json.loads(frontend_json.read_text(encoding="utf-8-sig"))
    if not isinstance(packages, dict):
        raise ValueError("Expected license-checker JSON object keyed by package@version")
    own_name = json.loads((repo_root / "gui/package.json").read_text())["name"]
    third_party = {k: v for k, v in packages.items() if not k.startswith(own_name + "@")}
    if not third_party or not any(k.startswith("leaflet@") for k in third_party):
        raise ValueError("Production dependency set is missing Leaflet or is empty")

    output = [
        "# Third-party software license notices",
        "",
        "Generated from resolved dependencies of app/Cargo.lock and gui/package-lock.json.",
        "Rust data: cargo-about. Frontend production data: license-checker.",
        "License text is reproduced from the installed packages or the cargo-about resolver.",
        "This report does not audit Windows SDK/WDK inputs, developer tools, locally sourced",
        "assets, hosted map services, or operating-system components.",
        "",
        "## Input lockfile fingerprints",
        "",
        "- Cargo.lock SHA-256: " + sha256(repo_root / "app/Cargo.lock"),
        "- package-lock.json SHA-256: " + sha256(repo_root / "gui/package-lock.json"),
        "",
        "## Rust dependency notices",
        "",
        rust_text,
        "",
        "## Frontend production dependency notices",
        "",
    ]
    for package_id in sorted(third_party, key=str.casefold):
        info = third_party[package_id]
        lic = str(info.get("licenses", "")).strip()
        if not lic or lic.upper() in {"UNKNOWN", "UNLICENSED", "NONE"}:
            raise ValueError(f"Unresolved license for {package_id}: {lic!r}")
        path_str = info.get("licenseFile")
        if not path_str:
            raise ValueError(f"Missing licenseFile for {package_id}")
        source = Path(path_str).resolve()
        node_modules = (repo_root / "gui/node_modules").resolve()
        if not source.is_file() or not source.is_relative_to(node_modules):
            raise ValueError(f"License file missing or outside installed frontend dependencies: {package_id}")
        content = source.read_text(encoding="utf-8-sig", errors="replace").strip()
        if len(content) < 50:
            raise ValueError(f"Unexpectedly short license text for {package_id}")
        block = fence(content)
        output.extend([
            "### " + package_id,
            "",
            "- SPDX/license expression reported by license-checker: " + lic,
            "- Package homepage/repository: " + str(info.get("repository") or info.get("url") or "Not declared"),
            "",
            block + "text",
            content,
            block,
            "",
        ])
    output.extend([
        "## Hosted map data",
        "",
        "The map UI requests standard OpenStreetMap tiles over HTTPS; those tiles are",
        "not bundled with Sarab. The map displays visible OpenStreetMap contributor",
        "attribution with a link to https://www.openstreetmap.org/copyright.",
        "Operators must also follow https://operations.osmfoundation.org/policies/tiles/.",
        "",
    ])
    return "\n".join(line.rstrip(" \t") for line in "\n".join(output).split("\n"))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rust", required=True, type=Path)
    parser.add_argument("--frontend-json", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    report = generate(args.rust, args.frontend_json, root)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")
    print(f"Notices generated: {args.output} ({len(report)} characters)")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, json.JSONDecodeError) as err:
        print(f"Third-party notice generation failed: {err}", file=sys.stderr)
        sys.exit(1)
